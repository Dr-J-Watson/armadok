"""Turning an event into a message and sending it through a channel."""

from __future__ import annotations

import hashlib
import hmac
import json
import re
import time
import uuid
from typing import Any, Literal

from cryptography.hazmat.primitives.asymmetric import ec
from pydantic import BaseModel, Field, model_validator

from armadok.core import outbound, webpush
from armadok.core.module import NotificationEvent

_PLACEHOLDER = re.compile(r"\{(\w{1,40})\}")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
DEFAULT_LANGUAGE = "en"
_PRIORITY = {"info": "3", "warning": "4", "critical": "5"}  # ntfy: 1 (min) .. 5 (max)


_MENTION = re.compile(r"(^|(?<=\s))@(?=\w)|<")
_MARKDOWN = re.compile(r"([\\*_~`|>#\[\]()!:.-])")
ZERO_WIDTH = "\u200b"


def neutralise(text: str, kind: str) -> str:
    """Make free text (a name typed by a user) harmless in a message for a `kind` of channel.

    A name must not ping a whole server (`@everyone`), open a mention or a link, or restyle the
    message. For every external channel an `@` that starts a word, and every `<` (mentions,
    Slack-style links), get an invisible character after them; for Discord the Markdown
    characters are also escaped. Plain-text channels keep the rest as typed.
    """
    text = _MENTION.sub(lambda m: (m.group(0) or "") + ZERO_WIDTH, text)
    if kind == "discord":
        text = _MARKDOWN.sub(r"\\\1", text)
    return text


def render(
    event: NotificationEvent, params: dict[str, Any], language: str, kind: str = ""
) -> tuple[str, str]:
    """Fill the event's template for `language` (falling back to English).

    Only `{name}` placeholders are replaced, by plain strings: nothing in a parameter can run or
    reach another object. With a channel `kind`, the values are neutralised for that channel
    (see `neutralise`); without one (the inbox, shown as plain text) they are used as they are.
    """
    title, body = event.templates.get(language) or event.templates[DEFAULT_LANGUAGE]

    def value(name: str) -> str:
        # Control characters (a newline in a node name, say) become spaces: they would break
        # headers and let a name forge extra lines in a message.
        text = _CONTROL.sub(" ", str(params.get(name, ""))[:200])
        return neutralise(text, kind) if kind else text

    def fill(text: str) -> str:
        return _PLACEHOLDER.sub(lambda m: value(m.group(1)), text)

    return fill(title), fill(body)


# --- channel configurations (validated before they are sealed) ------------------------------


class WebhookConfig(BaseModel):
    """A signed JSON webhook. The signing secret is generated by the server."""

    kind: Literal["webhook"] = "webhook"
    url: str = Field(max_length=2000)
    secret: str = ""


class NtfyConfig(BaseModel):
    """An ntfy topic on a server (the public one by default)."""

    kind: Literal["ntfy"] = "ntfy"
    server: str = Field(default="https://ntfy.sh", max_length=2000)
    topic: str = Field(pattern=r"^[A-Za-z0-9_-]{1,64}$")
    token: str = Field(default="", max_length=500, pattern=r"^[\x21-\x7e]*$")


class DiscordConfig(BaseModel):
    """A Discord channel webhook."""

    kind: Literal["discord"] = "discord"
    url: str = Field(max_length=2000)


_ADDRESS = r"^[A-Za-z0-9_+-]+(\.[A-Za-z0-9_+-]+)*@[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$"


class EmailConfig(BaseModel):
    """A mailbox reached through an SMTP server the account chooses."""

    kind: Literal["email"] = "email"
    host: str = Field(pattern=r"^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$")
    port: int = Field(ge=1, le=65535)
    security: Literal["starttls", "ssl", "none"] = "starttls"
    username: str = Field(default="", max_length=200, pattern=r"^[\x21-\x7e]*$")
    password: str = Field(default="", max_length=500, pattern=r"^[\x20-\x7e]*$")
    sender: str = Field(pattern=_ADDRESS, max_length=254)
    recipient: str = Field(pattern=_ADDRESS, max_length=254)

    @model_validator(mode="after")
    def _no_clear_password(self) -> EmailConfig:
        """Refuse credentials on a connection that is not encrypted."""
        if self.security == "none" and (self.username or self.password):
            raise ValueError("credentials need TLS")
        return self


class PushConfig(BaseModel):
    """One browser, as its push subscription describes it (the keys let only that browser read)."""

    kind: Literal["webpush"] = "webpush"
    endpoint: str = Field(max_length=2000, pattern=r"^https://[^\s]+$")
    p256dh: str = Field(pattern=r"^[A-Za-z0-9_-]{86,88}$")
    auth: str = Field(pattern=r"^[A-Za-z0-9_-]{22,24}$")

    @model_validator(mode="after")
    def _keys_are_what_they_claim(self) -> PushConfig:
        """Refuse a key that is not a P-256 point or a secret that is not 16 bytes."""
        point, secret = webpush.unb64u(self.p256dh), webpush.unb64u(self.auth)
        if len(point) != 65 or point[0] != 4 or len(secret) != 16:
            raise ValueError("bad subscription keys")
        # A key that is not a point of the curve is refused now, not at the first message.
        ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), point)
        return self


CONFIGS: dict[str, type[BaseModel]] = {
    "webpush": PushConfig,
    "email": EmailConfig,
    "webhook": WebhookConfig,
    "ntfy": NtfyConfig,
    "discord": DiscordConfig,
}


PUSH_PAD_BYTES = 1024  # every message is this long on the wire (the length would tell a lot)


def _push_message(title: str, body: str, event: str) -> bytes:
    """Return the JSON to push, cut so that it always fits in one encrypted record.

    Emoji and other characters outside the basic plane take 4 bytes each, so the limit is on
    bytes, not characters: the body is shortened first, then the title.
    """
    title, body = title[:120], body[:300]
    while True:
        data = json.dumps(
            {"title": title, "body": body, "event": event[:60]}, ensure_ascii=False
        ).encode()
        if len(data) <= webpush.MAX_PLAINTEXT:
            return data
        if body:
            body = body[: len(body) // 2]
        else:
            title = title[: max(1, len(title) // 2)]


async def _send_push(
    config: dict[str, Any],
    severity: str,
    title: str,
    body: str,
    event: str,
    key: Any,
    contact: str,
    allow_private: bool,
) -> None:
    """Encrypt a message for one browser and hand it to the push service named by its address.

    The text is plain: the service worker shows it as text, never as markup. A 404 or 410 means
    the browser unsubscribed (or the subscription expired): that is told apart so the person is
    shown "enable it again" rather than a vague failure.
    """
    message = _push_message(title, body, event)
    sealed = webpush.encrypt(
        message,
        webpush.unb64u(config["p256dh"]),
        webpush.unb64u(config["auth"]),
        pad_to=PUSH_PAD_BYTES,
    )
    headers = {
        "Content-Type": "application/octet-stream",
        "Content-Encoding": "aes128gcm",
        "TTL": "3600",
        "Urgency": "high" if severity == "critical" else "normal",
        "Authorization": webpush.vapid_header(key, config["endpoint"], contact),
    }
    status = await outbound.post(config["endpoint"], sealed, headers, allow_private)
    # With private addresses allowed, telling "gone" from "refused" would let an account probe
    # internal services one request at a time: only then is it kept vague.
    if status in (404, 410) and not allow_private:
        raise outbound.OutboundError("notifications.push_gone")
    if status >= 400:
        raise outbound.OutboundError("outbound.rejected")


def sign(secret: str, timestamp: str, body: bytes) -> str:
    """Return the HMAC-SHA256 signature receivers check (timestamp included, against replay)."""
    return hmac.new(secret.encode(), timestamp.encode() + b"." + body, hashlib.sha256).hexdigest()


async def send(
    config: dict[str, Any],
    *,
    event: str,
    severity: str,
    title: str,
    body: str,
    node_id: str | None,
    allow_private: bool,
    push_key: Any = None,
    push_contact: str = "",
) -> None:
    """Deliver one message through a channel. Raises `outbound.OutboundError` on failure."""
    kind = config["kind"]
    if kind == "webpush":
        await _send_push(
            config, severity, title, body, event, push_key, push_contact, allow_private
        )
        return
    if kind == "webhook":
        payload = json.dumps(
            {"event": event, "severity": severity, "title": title, "body": body, "node_id": node_id}
        ).encode()
        stamp = str(int(time.time()))
        headers = {
            "Content-Type": "application/json",
            "X-Armadok-Timestamp": stamp,
            "X-Armadok-Delivery": uuid.uuid4().hex,  # receivers can ignore a repeated delivery
            "X-Armadok-Signature": f"sha256={sign(config['secret'], stamp, payload)}",
        }
        status = await outbound.post(config["url"], payload, headers, allow_private)
    elif kind == "ntfy":
        headers = {
            "Title": title[:250].encode("ascii", "replace").decode(),
            "Priority": _PRIORITY[severity],
        }
        if config.get("token"):
            headers["Authorization"] = f"Bearer {config['token']}"
        url = f"{config['server'].rstrip('/')}/{config['topic']}"
        status = await outbound.post(url, body.encode(), headers, allow_private)
    elif kind == "email":
        await outbound.send_mail(
            host=config["host"],
            port=config["port"],
            security=config["security"],
            username=config.get("username", ""),
            password=config.get("password", ""),
            sender=config["sender"],
            recipient=config["recipient"],
            subject=f"[Armadok] {title}"[:200],
            body=f"{body}\n",
            allow_private=allow_private,
        )
        return
    elif kind == "discord":
        content = json.dumps(
            {
                "content": f"**{title}**\n{body}"[:1900],
                "allowed_mentions": {"parse": []},
                "flags": 4,  # no link previews: a name holding an address cannot embed anything
            }
        ).encode()
        status = await outbound.post(
            config["url"], content, {"Content-Type": "application/json"}, allow_private
        )
    else:
        raise outbound.OutboundError("notifications.unknown_channel")
    if status >= 400:
        # Not the exact status: with private addresses allowed it would let a user probe
        # internal services one request at a time.
        raise outbound.OutboundError("outbound.rejected")
